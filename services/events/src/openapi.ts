import {
  CategorySchema,
  CreateCategorySchema,
  CreateEventSchema,
  EventDetailSchema,
  EventListSchema,
  EventSearchResultSchema,
  ModerationEventListSchema,
  UpdateEventChatSchema,
  UpdateEventSchema,
  type ApiOperation,
} from '@event-sharing/contracts';
import { z } from 'zod';
import { EventReasonSchema } from './schemas/event-reason.schema.js';
import {
  ListEventsQuerySchema,
  ListOwnedEventsQuerySchema,
} from './schemas/list-events.schema.js';

export const schemas = { EventReasonSchema };

const tag = 'Events';
const transition = (
  action: string,
  summary: string,
  access: ApiOperation['access'] = 'organizer',
  body?: z.ZodType,
): ApiOperation => ({
  method: 'post',
  path: `/api/events/{eventId}/${action}`,
  tag,
  summary,
  access,
  ...(body ? { body } : {}),
  response: EventDetailSchema,
  description: 'Returns 202 while Participation applies a registration change.',
});

export const operations: ApiOperation[] = [
  {
    method: 'get',
    path: '/api/events/categories',
    tag,
    summary: 'List event categories',
    access: 'user',
    response: z.array(CategorySchema),
  },
  {
    method: 'post',
    path: '/api/events/categories',
    tag,
    summary: 'Create a category',
    access: 'admin',
    body: CreateCategorySchema,
    status: 201,
    response: CategorySchema,
  },
  {
    method: 'get',
    path: '/api/events',
    tag,
    summary: 'List published events',
    access: 'user',
    query: ListEventsQuerySchema,
    response: EventListSchema,
  },
  {
    method: 'post',
    path: '/api/events',
    tag,
    summary: 'Create a draft event',
    access: 'organizer',
    body: CreateEventSchema,
    status: 201,
    response: EventDetailSchema,
  },
  {
    method: 'get',
    path: '/api/events/mine',
    tag,
    summary: 'List events you organize',
    access: 'user',
    query: ListOwnedEventsQuerySchema,
    response: EventListSchema,
  },
  {
    method: 'get',
    path: '/api/events/mine/deletion-check',
    tag,
    summary: 'Check for active events before account deletion',
    access: 'user',
    response: z.object({ hasActiveEvents: z.boolean() }),
  },
  {
    method: 'get',
    path: '/api/events/mine/export',
    tag,
    summary: 'Export your events',
    access: 'user',
    response: z.object({ events: z.array(EventDetailSchema) }),
  },
  {
    method: 'get',
    path: '/api/events/moderation',
    tag,
    summary: 'List events waiting for moderation',
    access: 'admin',
    query: ListOwnedEventsQuerySchema,
    response: ModerationEventListSchema,
  },
  {
    method: 'get',
    path: '/api/events/organizer/{organizerId}',
    tag,
    summary: "List an organizer's published events",
    access: 'user',
    query: ListOwnedEventsQuerySchema,
    response: EventListSchema,
  },
  {
    method: 'get',
    path: '/api/events/{eventId}',
    tag,
    summary: 'Get an event',
    access: 'user',
    description:
      'Private venues show approximate coordinates to non-participants.',
    response: EventDetailSchema,
  },
  {
    method: 'patch',
    path: '/api/events/{eventId}',
    tag,
    summary: 'Edit an event',
    access: 'organizer',
    body: UpdateEventSchema,
    response: EventDetailSchema,
    description:
      'Returns 202 while Participation applies a registration change.',
  },
  {
    method: 'patch',
    path: '/api/events/{eventId}/chat',
    tag,
    summary: 'Turn the event chat on or off',
    access: 'organizer',
    body: UpdateEventChatSchema,
    response: EventDetailSchema,
  },
  transition('submit', 'Submit for moderation'),
  transition('approve', 'Approve after moderation', 'admin'),
  transition('reject', 'Reject with a reason', 'admin', EventReasonSchema),
  transition('publish', 'Publish an approved event'),
  transition('registration/open', 'Open registration'),
  transition('registration/close', 'Close registration'),
  transition('start', 'Mark the event as started'),
  transition('complete', 'Mark the event as completed'),
  transition('cancel', 'Cancel with a reason', 'organizer', EventReasonSchema),
  transition('archive', 'Archive the event'),
  {
    method: 'get',
    path: '/api/public/events/map',
    tag: 'Public',
    summary: 'Published events for the public map',
    access: 'public',
    query: z.object({
      limit: z.coerce.number().int().min(1).max(100).default(100),
    }),
    response: EventSearchResultSchema,
  },
  {
    method: 'get',
    path: '/api/public/events/{eventId}/availability',
    tag: 'Public',
    summary: 'Check that a public event exists',
    access: 'public',
    status: 204,
  },
];
