import {
  AddChatRoomMembersSchema,
  ChatMessageSchema,
  ChatOverviewSchema,
  ChatRoomSchema,
  CreateChatRoomSchema,
  MarkChatReadSchema,
  SendChatMessageSchema,
  UpdateChatNotificationPreferenceSchema,
  UpdateChatRoomSchema,
  type ApiOperation,
} from '@event-sharing/contracts';
import { z } from 'zod';

const tag = 'Chats';
const room = '/api/messages/events/{eventId}/rooms/{roomId}';

export const operations: ApiOperation[] = [
  {
    method: 'get',
    path: '/api/messages/overview',
    tag,
    summary: 'Your chats with unread counts',
    access: 'user',
    response: ChatOverviewSchema,
  },
  {
    method: 'get',
    path: '/api/messages/me/export',
    tag,
    summary: 'Export your chat messages',
    access: 'user',
  },
  {
    method: 'get',
    path: '/api/messages/events/{eventId}/rooms',
    tag,
    summary: 'Chat rooms of an event you can see',
    access: 'user',
  },
  {
    method: 'post',
    path: '/api/messages/events/{eventId}/rooms',
    tag,
    summary: 'Create a chat room',
    access: 'organizer',
    body: CreateChatRoomSchema,
    status: 201,
    response: ChatRoomSchema,
  },
  {
    method: 'patch',
    path: room,
    tag,
    summary: 'Rename or change a chat room',
    access: 'organizer',
    body: UpdateChatRoomSchema,
    response: ChatRoomSchema,
  },
  {
    method: 'patch',
    path: `${room}/archive`,
    tag,
    summary: 'Archive a chat room',
    access: 'organizer',
    response: ChatRoomSchema,
  },
  {
    method: 'patch',
    path: `${room}/notifications`,
    tag,
    summary: 'Turn chat notifications on or off',
    access: 'user',
    body: UpdateChatNotificationPreferenceSchema,
    response: z.object({ enabled: z.boolean() }),
  },
  {
    method: 'get',
    path: `${room}/members`,
    tag,
    summary: 'Members of a chat room',
    access: 'user',
  },
  {
    method: 'post',
    path: `${room}/members`,
    tag,
    summary: 'Add members to a chat room',
    access: 'organizer',
    body: AddChatRoomMembersSchema,
  },
  {
    method: 'delete',
    path: `${room}/members/{userId}`,
    tag,
    summary: 'Remove a member from a chat room',
    access: 'organizer',
    response: z.object({ removed: z.boolean() }),
  },
  {
    method: 'get',
    path: `${room}/messages`,
    tag,
    summary: 'Messages, newest first',
    access: 'user',
    query: z.object({ before: z.uuid().optional() }),
  },
  {
    method: 'post',
    path: `${room}/messages`,
    tag,
    summary: 'Send a message',
    access: 'user',
    body: SendChatMessageSchema,
    status: 201,
    response: ChatMessageSchema,
  },
  {
    method: 'patch',
    path: `${room}/read`,
    tag,
    summary: 'Mark messages as read',
    access: 'user',
    body: MarkChatReadSchema,
  },
];
